#ตัดเกรดนักเรียน(คําสั่งเงื่อนไข)
score = int(input("กรุณาป้อนคะเเนนสอบของคุณ:")) #รับข้อมูล
print("คะเเนนสอบของคุณ =",score) #เเสดงข้อมูลที่ได้

#process(กระบวนการ)
if score<0: #เงื่อนไขตรวจสอบคะเเนน
    print("กรอกคะเเนนไม่ถูกต้อง")
elif score>=50: #เงื่อนไขว่ามากกว่าหรือเท่ากับ50มั้ย
    print("คุณได้เกรด A") #ย่อหน้าเพื่อให้มันอยู่ในขอบเขตคําสั่งของ if
else: #เงื่อนไข
    print("คุณไม่ผ่านเกณ์") #ถ้าเงื่อนไขข้างบนไม่เป็นจริงมันก้จะปริ้นอันสุดท้ายเเทน
