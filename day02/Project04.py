#Ternary Operator(การลดรูป)
num=int(input("กรุณาป้อนตัวเลข:")) #ให้ input เข้าตัวเเปร num พร้อมครอบเเปลงเป็น int
print("ตัวเลขของคุณ คือ",num)

#รูปเเบบปกติ
if num%2==0: #ตัวเลขที่หาร 2 ลงตัว ไม่มีเศษเป็นเลขคู่
    print("เลขคู่")
else: #ถ้าไม่ลงตัวก้จะปริ้นเงื่อนไขตัวที่ 2
    print("เลขคี")

#การลดรูป
print("เลขคู่") if num%2==0 else print("เลขคี่")
