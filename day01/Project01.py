#ข้อมูลนักเรียน (input)
name="Aom" 
age=15
grade=3.80
status=True
#ตัวเเปรในบรรทัดเดียว
name,age,grade,status="Aom",15,3.80,True
#เเสดงข้อมูล (output)
print("name =",name) #ปริ้นตัวเเปร name 
                     #"name =", คือคําที่จะอยู่ด้านหน้าตัวเเปร name
print("age =",age) #ปริ้นตัวเเปร age
print("grade =",grade) #ปริ้นตัวเเปร grade
print("status =",status) #ปริ้นตัวเเปร status