#การสร้างฟังก์ชัน
def use(time,nameuu,age): #parameter ตัวเเปรรับ
    print("สวัสดี",time,nameuu) #ส่งที่จะให้ทํา
    print("ปีนี้คุณมีอายุ",age,"ปี")

def shw(num): #def ชื่อฟังก์ชัน(ตัวเเปร):
    print("----เเม่",num,"-----") #สิ่งที่จะให้ทํา
    for i in range(1,13):
        print(num,"x",i,"=",num*i)

#การเรียกใช้งาน
time="ตอนเช้า" #พิมตัวเเปรเข้าไปเลย
use(time,"ออมม",15) #arguments ตัวเเปรส่ง
use(time,"เเมวว",16) #ตัวเเปรส่ง
shw(4) #ป้อนข้อมูลที่จะให้เเสดงลงไป
shw(5) #สามารถป้อนได้หลายข้อมูล

"""
"ฟังก์ชันกําหนดค่าเริ่มต้น"
"""
def gg(tuii,dftt,mumy=35000): #=35000 เป็นการกําหนดเงินเดือนค่าเริ่มต้น
    print("ชื่อพนักงาน",tuii,"เเผนก",dftt)
    print("เงินเดือน",mumy)
    print("-------------")
gg("ออม","ไซเบอร์สีเคียว",40000)
gg("ม่อน","ไอที") #ถ้าไม่ระบุเงินเดือนเวลารันมันก้จะเด้งให้เป็น 35000เองเลย

"""
"Argumunts(เเบบลําดับ(*args))"
"""
print("ฟังก์ชัน( * อะไรก้ได้ )")
def gy(*t): #ใช้เเทน parameter ยาวๆ
    print("ชื่อพนักงาน",t[0],"เเผนก",t[1]) #ใช้เลข0-n เพื่อกําหนดลําดับเเทน
    print("เงินเดือน",t[2]) #t[n]
    print("-------------")

gy("ออม","ไซเบอร์สีเคียว",40000) #0คือชื่อ 1คือเเผนก 2คือเงินเดือน
gy("ม่อน","ไอที",45000)

"""
"Argumunts(เเบบกําหนดชื่อ(**kwargs))"
สําหรับคนสับสนในเลข
"""
print("ฟังก์ชัน( ** อะไรก้ได้ )")
def gy(**pol): #ใช้เเทน parameter ยาวๆ
    print("ชื่อพนักงาน",pol["nnn"],"เเผนก",pol["ddd"]) #ใช้ ชื่อเพื่อกําหนดลําดับเเทน
    print("เงินเดือน",pol["sss"]) #pol["sss"]
    print("-------------")

gy(nnn="ออม",ddd="ไซเบอร์สีเคียว",sss=40000) #0คือชื่อ 1คือเเผนก 2คือเงินเดือน
gy(nnn="ม่อน",ddd="ไอที",sss=45000)

