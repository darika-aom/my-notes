def citnum(mmm): #สร้างฟังก์ชันชื่อ citnum ที่ต้องรับตัวแปรพารามิเตอร์ชื่อ mmm เข้ามา
    if mmm%2==0: #เช็คว่าเอาค่า mmm ไปหาร 2 แล้วเหลือเศษ 0 หรือไม่
        return "เลขคู่" #ถ้าใช่ จะ return คำว่า "เลขคู่" กลับออกไป
    else:
        return "เลขคี่" #ถ้าไม่ใช่ return คำว่า "เลขคี่" กลับออกไป

rettt = citnum(4) #เรียกใช้ฟังก์ชัน ส่งเลข 4 เข้าไปคำนวณ แล้วเอาผลลัพธ์ที่รีเทิร์นกลับมาเก็บไว้ในตัวแปร rettt
print("ผลลัพธ์ =",rettt)