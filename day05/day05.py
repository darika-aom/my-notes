passwords="root"
with open("words.txt","r",encoding="utf-8") as file:
    for line in file:
        pp=line.strip()
        print("กําลังลองรหัส:",pp)       
        if pp==passwords: #เงื่อนไข
            print ("เจาะระบบสําเร็จ รหัสผ่านคือ",passwords)
            break #ถ้าเจอก้จะหยุดการทํางาน       
    else: #ถ้าไม่เจอก้จะปริ้นว่าไม่พบรหัส
        print ("ไม่พบรหัสผ่าน")    

