#สรุปวิธีอ่านไฟล์ที่เป้นสกุล.txt (ใช้ไฟล์.pyอ่าน)

#"คําสั่งเปิดไฟล์ เเบบที่1"
file=open("ชื่อไฟล์.txt") #ถ้าไฟล์มีภาษาไทยให้พิม ,encoding="utf-8"
#คําสั่งอ่านไฟล์
print(file.read())
#ข้อเสียคืออ่านเสร็จต้องปิดไฟล์ทุกครั้งไม่งั้นจะ Error
file.close()

#"คําสั่งเปิดไฟล์ เเบบที่2"
with open("ชื่อไฟล์.txt","r",encoding="utf-8") as file:
    print(file.read())
    #อันนี้มันจะปิดไฟล์ให้เอง

#"เขียนไฟล์ทับเข้าไป"  
with open("ชื่อไฟล์.txt","w",encoding="utf-8") as file:
    file.write("รหัสเทสคับไอหรรม")

#"เขียนไฟล์เพิ่มเข้าไป ต่อท้ายอันเดิม"
with open("ชื่อไฟล์.txt","a",encoding="utf-8") as file:
    file.write("รหัสเทสคับไอหรรม")

#"สร้างไฟล์ใหม่ เเล้วเขียนเนื้อหาเข้าไป"
with open("ชื่อไฟล์ใหม่.txt","x",encoding="utf-8") as file:
    file.write("676767")

